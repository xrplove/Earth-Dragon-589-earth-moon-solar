import assert from 'node:assert/strict';
import { createTextTransition } from '../src/text-transition.js';
globalThis.matchMedia=()=>({matches:false});
const animations=[],applied=[];
const container={animate(){let finish;const finished=new Promise(resolve=>finish=resolve);const animation={finished,finish,cancel(){}};animations.push(animation);return animation;}};
const transition=createTextTransition(container,value=>applied.push(value));
const flush=()=>new Promise(resolve=>setImmediate(resolve));
transition('A','A');transition('B','B');transition('A','A');
animations[0].finish();await flush();animations[1].finish();await flush();
assert.deepEqual(applied,['A'],'Returning to the shown title must not reapply it');
transition('B','B');transition('C','C');transition('C','C');
animations[2].finish();await flush();
assert.deepEqual(applied,['A','C'],'Fade-out must coalesce to the latest title');
transition('D','D');transition('C','C');
animations[3].finish();await flush();
assert.equal(animations.length,4,'Returning to the incoming title must discard stale queued changes');
for(let i=0;i<100;i++)transition('C','C');
assert.equal(animations.length,4,'Identical updates must not replay animation');
globalThis.matchMedia=()=>({matches:true});transition('E','E');await flush();
assert.deepEqual(applied,['A','C','E']);assert.equal(animations.length,4);
console.log('PASS: rapid reversals, latest-title coalescing, incoming-title deduplication, stable repeated updates, and reduced motion.');
